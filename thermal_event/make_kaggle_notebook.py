"""Build e0_kaggle.ipynb: a self-contained Kaggle notebook that runs E0 on M2DGR bags.

The repo is private, so the notebook carries its own copy of the code. Rerun this script after
changing any of the .py files it embeds:  python make_kaggle_notebook.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip()}


def code(text):
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": text.strip()}


cells = [
    md("""
# E0 on M2DGR (Kaggle)

Settings before running: **Internet on** (needs a phone-verified Kaggle account). Accelerator: GPU T4
for the YOLO step; CPU is enough for the summary.

Bags are 10 to 15 GB. They go to temporary disk (`/kaggle/temp`), not `/kaggle/working`, which is
kept after the session but capped at about 20 GB. Results (a few MB) go to `/kaggle/working`.
Do one bag at a time: download, run, delete.

Generated by `thermal_event/make_kaggle_notebook.py`; edit the .py files there, not this notebook.
"""),
    code("!pip install -q rosbags ultralytics\n!df -h /kaggle/working /kaggle/temp 2>/dev/null || df -h /kaggle/working"),
]
for name in ("storage.py", "labels.py", "bag_io.py", "simulate.py", "e0_inspect.py", "build_cache.py"):
    cells.append(code(f"%%writefile {name}\n" + (HERE / name).read_text()))
cells += [
    md("""
## Download one bag

OneDrive only serves the file to a logged-in browser, so copy the browser's request and run it here:

1. Open the bag's Rosbag link (M2DGR README, Indoors table) in Chrome.
2. Open developer tools (⌥⌘I on Mac, F12 on Windows) and pick the **Network** tab.
3. Click **Download** on the OneDrive page.
4. In the Network list, right-click the request named `download.aspx...` (or the one with the bag's
   name), then **Copy → Copy as cURL (bash)**. Cancel the download in Chrome.
5. Paste it into the next cell in place of the example, and add `-L -o "$BAG"` at the very end.

The copied command contains your login cookies: don't share it or save it anywhere, and run it soon.
"""),
    code("""
NAME = "room_01"   # used for file and output names
DATASET = "m2dgr"  # or "vivid" for ViViD++
import os
os.makedirs("/kaggle/temp", exist_ok=True)
BAG = f"/kaggle/temp/{NAME}.bag"
os.environ["BAG"] = BAG
"""),
    code("""
%%bash
# ViViD++ (plain link from the request email): wget -q --show-progress -O "$BAG" 'PASTE_LINK_HERE'
# M2DGR: replace the line below with the copied cURL command, then add: -L -o "$BAG"
curl 'PASTE_COPIED_URL_HERE' -L -o "$BAG"
"""),
    code("""
with open(BAG, "rb") as f:
    head = f.read(13)
assert head == b"#ROSBAG V2.0\\n", f"not a rosbag (got {head!r}); copy the request again"
print(f"{BAG}: {os.path.getsize(BAG) / 1e9:.1f} GB")
"""),
    md("## Check topics\n\nCopy this output back: it confirms topic names, message types and the thermal encoding."),
    code("!python e0_inspect.py $BAG --dataset $DATASET --summary-only"),
    md("## Full E0: sync check, sample images, auto-labels and class distribution"),
    code("!python e0_inspect.py $BAG --dataset $DATASET --out /kaggle/working/e0_$NAME --yolo yolov8x.pt"),
    code("""
from IPython.display import Image, display
import glob
print(open(f"/kaggle/working/e0_{NAME}/summary.txt").read())
for p in sorted(glob.glob(f"/kaggle/working/e0_{NAME}/samples/*.png"))[:4]:
    display(Image(p))
"""),
    md("## Free the disk before the next bag"),
    code("os.remove(BAG)\n!df -h /kaggle/temp 2>/dev/null || df -h /"),
]

nb = {"cells": cells, "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3",
                                                  "language": "python"}},
      "nbformat": 4, "nbformat_minor": 5}
for c in nb["cells"]:  # notebooks store source as a list of lines
    c["source"] = c["source"].splitlines(keepends=True)
(HERE / "e0_kaggle.ipynb").write_text(json.dumps(nb, indent=1) + "\n")
print("wrote e0_kaggle.ipynb")
